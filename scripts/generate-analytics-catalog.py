#!/usr/bin/env python3
"""Generate the closed analytics enums. --check detects cross-platform drift."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
catalog = json.loads((ROOT / "docs/analytics-catalog.json").read_text())
assert catalog["version"] == 1 and len(catalog["families"]) == 10
metrics = [f"{family}.{variant}" for family, variants in catalog["families"].items() for variant in variants]
assert len(metrics) == len(set(metrics))
def camel(value):
    parts = value.replace(".", "_").split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])

outputs = {
    "backend/convex/lib/analyticsCatalog.ts": "// Generated by scripts/generate-analytics-catalog.py.\nexport const ANALYTICS_VERSION = 1;\nexport const METRICS = " + json.dumps(metrics, indent=2) + " as const;\nexport type AnalyticsMetric = typeof METRICS[number];\n",
    "ios/Hadithly/Core/Analytics/AnalyticsMetric.swift": "// Generated by scripts/generate-analytics-catalog.py.\nimport Foundation\n\nenum AnalyticsMetric: String, Codable, CaseIterable {\n" + "".join(f'    case {camel(m)} = "{m}"\n' for m in metrics) + "}\n",
    "android/app/src/main/kotlin/com/hadithly/app/core/analytics/AnalyticsMetric.kt": "// Generated by scripts/generate-analytics-catalog.py.\npackage com.hadithly.app.core.analytics\n\nenum class AnalyticsMetric(val wire: String) {\n" + ",\n".join(f'    {camel(m)}("{m}")' for m in metrics) + ";\n}\n",
}
check = argparse.ArgumentParser()
check.add_argument("--check", action="store_true")
args = check.parse_args()
for name, content in outputs.items():
    path = ROOT / name
    if args.check:
        assert path.exists() and path.read_text() == content, f"Catalog drift: {name}"
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
print(f"Validated {len(metrics)} variants in ten event families")
